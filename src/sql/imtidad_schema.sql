-- ============================================================
-- IMTIDAD (امتداد) — Full Oracle Database Schema
-- ============================================================
-- This script creates the complete normalized schema described
-- in the IMTIDAD system architecture. The PROJECT table columns
-- are aligned with the current ProjectRepository implementation.
--
-- Run this script as SYSTEM (or a privileged schema user) before
-- starting the application.
-- ============================================================

-- ------------------------------------------------------------
-- 1. Reference Data Tables
-- ------------------------------------------------------------

CREATE TABLE DEPARTMENT (
                            dept_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            dept_name VARCHAR2(100) NOT NULL
);

CREATE TABLE COURSE (
                        course_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        course_name VARCHAR2(100) NOT NULL,
                        course_code VARCHAR2(20),
                        dept_id NUMBER,
                        CONSTRAINT fk_course_dept FOREIGN KEY (dept_id) REFERENCES DEPARTMENT(dept_id)
);

CREATE TABLE ROLE (
                      role_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      role_name VARCHAR2(50) NOT NULL
);

CREATE TABLE USER_ACCOUNT (
                              user_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              username VARCHAR2(50) NOT NULL UNIQUE,
                              email VARCHAR2(100) NOT NULL UNIQUE,
                              password_hash VARCHAR2(255) NOT NULL,
                              role_id NUMBER,
                              CONSTRAINT fk_user_role FOREIGN KEY (role_id) REFERENCES ROLE(role_id)
);

-- Student-only information is intentionally separated from USER_ACCOUNT so
-- reviewer and administrator accounts cannot be self-created as students.
CREATE TABLE STUDENT_PROFILE (
                                 user_id NUMBER PRIMARY KEY,
                                 full_name VARCHAR2(150) NOT NULL,
                                 student_number VARCHAR2(30) NOT NULL UNIQUE,
                                 department_id NUMBER NOT NULL,
                                 CONSTRAINT fk_student_user FOREIGN KEY (user_id) REFERENCES USER_ACCOUNT(user_id) ON DELETE CASCADE,
                                 CONSTRAINT fk_student_department FOREIGN KEY (department_id) REFERENCES DEPARTMENT(dept_id)
);

-- ------------------------------------------------------------
-- 2. Core Project Tables
-- ------------------------------------------------------------

CREATE TABLE PROJECT (
                         project_id NUMBER PRIMARY KEY,
                         title VARCHAR2(200) NOT NULL,
                         problem_statement CLOB,
                         publication_status VARCHAR2(50) DEFAULT 'DRAFT' NOT NULL,
                         project_type VARCHAR2(50) NOT NULL,
                         owner_id NUMBER,
                         reviewer_id NUMBER,
                         repository_url VARCHAR2(500),
                         created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                         CONSTRAINT fk_project_owner FOREIGN KEY (owner_id) REFERENCES USER_ACCOUNT(user_id),
                         CONSTRAINT fk_project_reviewer FOREIGN KEY (reviewer_id) REFERENCES USER_ACCOUNT(user_id),
                         CONSTRAINT chk_project_status CHECK (publication_status IN ('DRAFT','PENDING_REVIEW','NEEDS_CHANGES','APPROVED','PUBLISHED')),
                         CONSTRAINT chk_project_type CHECK (project_type IN ('COURSE_PROJECT','GRADUATION_PROJECT'))
);

CREATE TABLE COURSE_PROJECT_DETAILS (
                                        detail_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        project_id NUMBER NOT NULL,
                                        course_id NUMBER,
                                        course_instructor VARCHAR2(100),
                                        semester VARCHAR2(20),
                                        academic_year NUMBER,
                                        CONSTRAINT fk_cp_project FOREIGN KEY (project_id) REFERENCES PROJECT(project_id) ON DELETE CASCADE,
                                        CONSTRAINT fk_cp_course FOREIGN KEY (course_id) REFERENCES COURSE(course_id)
);

CREATE TABLE GRADUATION_PROJECT_DETAILS (
                                            gp_detail_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                            project_id NUMBER NOT NULL,
                                            advisor VARCHAR2(100),
                                            academic_year NUMBER,
                                            graduation_term VARCHAR2(20),
                                            defense_date DATE,
                                            department_id NUMBER,
                                            CONSTRAINT fk_gp_project FOREIGN KEY (project_id) REFERENCES PROJECT(project_id) ON DELETE CASCADE,
                                            CONSTRAINT fk_gp_department FOREIGN KEY (department_id) REFERENCES DEPARTMENT(dept_id)
);

CREATE TABLE PROJECT_MEMBER (
                                member_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                project_id NUMBER NOT NULL,
                                user_id NUMBER,
                                member_name VARCHAR2(100) NOT NULL,
                                member_role VARCHAR2(50),
                                CONSTRAINT fk_member_project FOREIGN KEY (project_id) REFERENCES PROJECT(project_id) ON DELETE CASCADE,
                                CONSTRAINT fk_member_user FOREIGN KEY (user_id) REFERENCES USER_ACCOUNT(user_id)
);

-- ------------------------------------------------------------
-- 3. Content & Technology Tables
-- ------------------------------------------------------------

CREATE TABLE TECHNOLOGY (
                            tech_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            tech_name VARCHAR2(50) NOT NULL UNIQUE
);

CREATE TABLE PROJECT_TECHNOLOGY (
                                    project_id NUMBER NOT NULL,
                                    tech_id NUMBER NOT NULL,
                                    CONSTRAINT fk_pt_project FOREIGN KEY (project_id) REFERENCES PROJECT(project_id) ON DELETE CASCADE,
                                    CONSTRAINT fk_pt_tech FOREIGN KEY (tech_id) REFERENCES TECHNOLOGY(tech_id) ON DELETE CASCADE,
                                    CONSTRAINT pk_project_tech PRIMARY KEY (project_id, tech_id)
);

CREATE TABLE PROJECT_FILE (
                              file_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              project_id NUMBER NOT NULL,
                              file_name VARCHAR2(255) NOT NULL,
                              file_path VARCHAR2(500) NOT NULL,
                              file_type VARCHAR2(50),
                              uploaded_by NUMBER,
                              uploaded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                              CONSTRAINT fk_file_project FOREIGN KEY (project_id) REFERENCES PROJECT(project_id) ON DELETE CASCADE,
                              CONSTRAINT fk_file_user FOREIGN KEY (uploaded_by) REFERENCES USER_ACCOUNT(user_id)
);

-- ------------------------------------------------------------
-- 4. Review & Quality Tables
-- ------------------------------------------------------------

CREATE TABLE REVIEW (
                        review_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        project_id NUMBER NOT NULL,
                        reviewer_id NUMBER,
                        decision VARCHAR2(50),
                        comments CLOB,
                        problem_clarity NUMBER(1),
                        datasets_valid NUMBER(1),
                        ownership_proof NUMBER(1),
                        file_integrity NUMBER(1),
                        reviewed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                        CONSTRAINT fk_review_project FOREIGN KEY (project_id) REFERENCES PROJECT(project_id) ON DELETE CASCADE,
                        CONSTRAINT fk_review_user FOREIGN KEY (reviewer_id) REFERENCES USER_ACCOUNT(user_id),
                        CONSTRAINT chk_review_decision CHECK (decision IN ('APPROVE','REQUEST_CHANGES','REJECT'))
);

-- ------------------------------------------------------------
-- 5. Continuation & Lineage Tables
-- ------------------------------------------------------------

CREATE TABLE CONTINUATION_OPPORTUNITY (
                                          opportunity_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                          project_id NUMBER NOT NULL,
                                          goals CLOB,
                                          expected_timeline VARCHAR2(255),
                                          required_skills CLOB,
                                          created_by NUMBER,
                                          created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                                          CONSTRAINT fk_opp_project FOREIGN KEY (project_id) REFERENCES PROJECT(project_id) ON DELETE CASCADE,
                                          CONSTRAINT fk_opp_user FOREIGN KEY (created_by) REFERENCES USER_ACCOUNT(user_id)
);

CREATE TABLE CONTINUATION_REQUEST (
                                      request_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                      project_id NUMBER NOT NULL,
                                      requester_id NUMBER,
                                      goals CLOB,
                                      expected_timeline VARCHAR2(255),
                                      skill_set CLOB,
                                      request_status VARCHAR2(50) DEFAULT 'SUBMITTED',
                                      submitted_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                                      CONSTRAINT fk_cont_project FOREIGN KEY (project_id) REFERENCES PROJECT(project_id) ON DELETE CASCADE,
                                      CONSTRAINT fk_cont_user FOREIGN KEY (requester_id) REFERENCES USER_ACCOUNT(user_id),
                                      CONSTRAINT chk_cont_status CHECK (request_status IN ('SUBMITTED','UNDER_REVIEW','APPROVED','REJECTED','WITHDRAWN'))
);

CREATE TABLE CONTINUATION_REQUEST_DETAIL (
                                             request_id NUMBER PRIMARY KEY,
                                             proposed_title VARCHAR2(200) NOT NULL,
                                             relation_type VARCHAR2(50) DEFAULT 'CONTINUATION' NOT NULL,
                                             repository_url VARCHAR2(500),
                                             attachment_path VARCHAR2(500),
                                             review_notes CLOB,
                                             reviewer_id NUMBER,
                                             reviewed_at TIMESTAMP,
                                             child_project_id NUMBER,
                                             CONSTRAINT fk_cont_detail_request FOREIGN KEY (request_id) REFERENCES CONTINUATION_REQUEST(request_id) ON DELETE CASCADE,
                                             CONSTRAINT fk_cont_detail_reviewer FOREIGN KEY (reviewer_id) REFERENCES USER_ACCOUNT(user_id),
                                             CONSTRAINT fk_cont_detail_child FOREIGN KEY (child_project_id) REFERENCES PROJECT(project_id),
                                             CONSTRAINT chk_cont_detail_relation CHECK (relation_type IN ('CONTINUATION','EXTENSION','DERIVATIVE'))
);

CREATE TABLE PROJECT_RELATION (
                                  relation_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  parent_project_id NUMBER NOT NULL,
                                  child_project_id NUMBER NOT NULL,
                                  relation_type VARCHAR2(50) DEFAULT 'CONTINUATION',
                                  CONSTRAINT fk_relation_parent FOREIGN KEY (parent_project_id) REFERENCES PROJECT(project_id) ON DELETE CASCADE,
                                  CONSTRAINT fk_relation_child FOREIGN KEY (child_project_id) REFERENCES PROJECT(project_id) ON DELETE CASCADE,
                                  CONSTRAINT chk_relation_type CHECK (relation_type IN ('CONTINUATION','EXTENSION','DERIVATIVE'))
);

-- ------------------------------------------------------------
-- 6. Audit Log
-- ------------------------------------------------------------

CREATE TABLE AUDIT_LOG (
                           log_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           user_id NUMBER,
                           action_performed VARCHAR2(255) NOT NULL,
                           entity_type VARCHAR2(50),
                           entity_id NUMBER,
                           action_timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                           CONSTRAINT fk_log_user FOREIGN KEY (user_id) REFERENCES USER_ACCOUNT(user_id)
);

